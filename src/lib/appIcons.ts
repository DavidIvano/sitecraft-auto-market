export function refreshAppIcons(root: ParentNode = document) {
  createIcons({
    icons: APP_ICONS,
    attrs: { width: 18, height: 18, "stroke-width": 2 },
    root: root as Document,
  });
}

let appIconsInstalled = false;

export function installAppIcons(root: ParentNode = document) {
  refreshAppIcons(root);

  if (appIconsInstalled || typeof window === "undefined") return;
  appIconsInstalled = true;
  window.addEventListener("app-icons-refresh", () => refreshAppIcons(document));
}
